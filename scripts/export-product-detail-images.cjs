const fs = require('node:fs');
const path = require('node:path');
const { root, openBrowser } = require('./millet-browser.cjs');

(async () => {
  const base = 'assets/images/product-details';
  const groups = {};
  for (const file of ['manifest-a.json', 'manifest-b.json']) {
    const full = path.join(root, base, file);
    if (!fs.existsSync(full)) continue;
    const manifest = JSON.parse(fs.readFileSync(full, 'utf8').replace(/^\uFEFF/, ''));
    if (Array.isArray(manifest)) {
      for (const item of manifest) (groups[item.id] ||= []).push(item);
    } else Object.assign(groups, manifest);
  }
  const shared = JSON.parse(fs.readFileSync(path.join(root,base,'shared/manifest.json'),'utf8'));
  groups.shared = shared;
  const browser = await openBrowser();
  const output = {};
  const audit = [];
  try {
    await browser.navigate('/__canvas');
    for (const [id, photos] of Object.entries(groups)) {
      output[id] = [];
      const destination = path.join(root, base, id);
      fs.mkdirSync(destination, {recursive:true});
      for (const photo of photos) {
        const source = photo.path;
        const metadata = await browser.evaluate(`(async()=>{const image=new Image();image.src=${JSON.stringify('/'+source)};await image.decode();window.exportImage=image;return {width:image.naturalWidth,height:image.naturalHeight};})()`);
        const widths = [...new Set([320,480,960,1440].map(w=>Math.min(w,metadata.width)))];
        const variants = [];
        for (const width of widths) {
          const height = Math.round(width*metadata.height/metadata.width);
          const name = photo.role+'-'+width+'.webp';
          const target = path.join(destination,name);
          if (!fs.existsSync(target) || fs.statSync(target).mtimeMs < fs.statSync(path.join(root,source)).mtimeMs) {
            const data = await browser.evaluate(`(()=>{const c=document.createElement('canvas');c.width=${width};c.height=${height};const ctx=c.getContext('2d');ctx.imageSmoothingQuality='high';ctx.drawImage(window.exportImage,0,0,c.width,c.height);return c.toDataURL('image/webp',.86).split(',')[1];})()`);
            fs.writeFileSync(target,Buffer.from(data,'base64'));
          }
          variants.push({src:base+'/'+id+'/'+name,width,height});
        }
        const fourK = photo.role+'-4k-upscaled.jpg';
        const fourKPath = path.join(destination,fourK);
        if(!fs.existsSync(fourKPath) || fs.statSync(fourKPath).mtimeMs < fs.statSync(path.join(root,source)).mtimeMs) {
          const large = await browser.evaluate(`(()=>{const c=document.createElement('canvas');c.width=3840;c.height=Math.round(3840*window.exportImage.naturalHeight/window.exportImage.naturalWidth);const ctx=c.getContext('2d');ctx.imageSmoothingQuality='high';ctx.drawImage(window.exportImage,0,0,c.width,c.height);return c.toDataURL('image/jpeg',.93).split(',')[1];})()`);
          fs.writeFileSync(fourKPath,Buffer.from(large,'base64'));
        }
        const preferred=variants.find(v=>v.width===960)||variants.at(-1);
        const record={role:photo.role,src:preferred.src,srcset:variants.map(v=>v.src+' '+v.width+'w').join(', '),thumb:variants[0].src,master:source,alt:photo.alt||id.replaceAll('-',' ')+' '+photo.role,width:metadata.width,height:metadata.height};
        output[id].push(record);
        audit.push({...photo,id,nativeSize:[metadata.width,metadata.height],variants,export4k:{path:base+'/'+id+'/'+fourK,width:3840,height:Math.round(3840*metadata.height/metadata.width),upscaled:metadata.width<3840}});
      }
      console.log('Exported '+id+': '+photos.length+' photographs');
    }
    delete output.shared;
    fs.writeFileSync(path.join(root,'assets/js/product-images.js'),'// Generated by scripts/export-product-detail-images.cjs. Original masters retained.\nconst PRODUCT_DETAIL_IMAGES = '+JSON.stringify(output,null,2)+';\n');
    fs.writeFileSync(path.join(root,base,'exports.json'),JSON.stringify(audit,null,2)+'\n');
  } finally { browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
